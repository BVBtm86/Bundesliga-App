import {test,expect} from "@playwright/test";

test("historical matrix opens an across-season modal and scatter axes are independent",async({page,isMobile})=>{
 test.setTimeout(120000);
 await page.addInitScript(()=>localStorage.setItem("bundesliga-theme","dark"));
 await page.goto("/teams");
 await page.locator(".team-directory-card").first().click();
 await page.getByRole("tab",{name:"Season Evolution",exact:true}).click();
 const workspace=page.locator(".season-evolution-workspace");
 const navigation=workspace.getByRole("navigation",{name:"Season Evolution analytical sections"});
 await expect(navigation.getByRole("button")).toHaveText(["Summary","Evolution","Spatial Analysis","Tactical Analysis"]);
 await expect(page).toHaveURL(/\/season-evolution$/);
 const url=page.url();
 await navigation.getByRole("button",{name:"Evolution",exact:true}).click();
 await expect(page).toHaveURL(url);
 const matrix=workspace.getByRole("region",{name:"Historical statistical matrix",exact:true});
 await expect(matrix).toBeVisible({timeout:90000});
 const headers=await matrix.locator("thead th").allTextContents();
 expect(headers.length).toBeGreaterThan(18);
 expect(headers[0]).toBe("Metric");
 expect(headers.at(-2)).toBe("Trend");
 expect(headers.at(-1)).toBe("Vs historical avg");
 const years=headers.slice(1,-2).map(value=>parseInt(value));
 expect(years).toEqual([...years].sort((a,b)=>b-a));
 await expect(matrix.locator(".research-trend-cell svg")).toHaveCount(0);
 expect((await matrix.locator(".research-trend-cell").allTextContents()).every(text=>/^(Increasing|Decreasing|Stable|Insufficient)$/.test(text))).toBe(true);
 expect(headers).not.toContain("Historical avg");
 await expect(workspace.locator(".historical-selected-seasons")).toHaveCount(0);
 await expect(matrix.locator(".research-trend-cell").first()).toBeVisible();
 await expect(page.getByRole("dialog")).toHaveCount(0);
 await expect(workspace.getByRole("img",{name:"Goals across seasons",exact:true})).toHaveCount(0);
 const scatter=workspace.locator(".historical-season-comparison");
 for(const name of ["X-axis category","X-axis metric","Y-axis category","Y-axis metric"])await expect(scatter.getByRole("combobox",{name,exact:true})).toBeVisible();
 const scatterBounds=await scatter.boundingBox();
 for(const select of await scatter.getByRole("combobox").all()) {const box=await select.boundingBox();expect(box!.x+box!.width).toBeLessThanOrEqual(scatterBounds!.x+scatterBounds!.width+1);}
 await expect(scatter.getByLabel("Regression",{exact:true})).toHaveCount(0);
 await expect(scatter.getByLabel("Correlations",{exact:true})).toHaveCount(0);
 await scatter.getByLabel("X-axis category",{exact:true}).selectOption("passing");
 await scatter.getByLabel("X-axis metric",{exact:true}).selectOption("passAccuracy");
 await scatter.getByLabel("Y-axis category",{exact:true}).selectOption("results");
 await scatter.getByLabel("Y-axis metric",{exact:true}).selectOption("pointsPerMatch");
 const scatterPoints=scatter.locator('g[role="button"]');
 const actualDescriptions=await scatterPoints.evaluateAll(nodes=>nodes.map(node=>node.getAttribute("aria-label")));
 await workspace.getByLabel("Table display",{exact:true}).selectOption("index");
 await expect.poll(()=>scatterPoints.evaluateAll(nodes=>nodes.map(node=>node.getAttribute("aria-label")))).toEqual(actualDescriptions);
 await workspace.getByLabel("Table display",{exact:true}).selectOption("rank");
 await expect.poll(()=>scatterPoints.evaluateAll(nodes=>nodes.map(node=>node.getAttribute("aria-label")))).toEqual(actualDescriptions);
 await workspace.getByLabel("Table display",{exact:true}).selectOption("actual");
 await matrix.locator("tbody tr").first().locator("td").first().click();
 const modal=page.getByRole("dialog");
 await expect(modal).toBeVisible();
 await expect(modal.getByRole("heading",{name:"Goals",exact:true})).toBeVisible();
 await expect(modal.locator(".historical-modal-club img")).toBeVisible();
 await expect(modal.locator(".historical-modal-values dt")).toHaveText(["Current season","Historical average","Vs historical average"]);
 await expect(modal.getByRole("img",{name:"Goals across seasons",exact:true})).toBeVisible();
 await expect(modal.getByText("Matchday progression",{exact:true})).toHaveCount(0);
 const seasonOrder=await modal.locator("svg > g").last().locator("circle[aria-label]").evaluateAll(nodes=>nodes.map(node=>node.getAttribute("aria-label")?.match(/\d{4}\/\d{4}/)?.[0]??""));
 expect(seasonOrder.length).toBeGreaterThan(1);
 expect(seasonOrder).toEqual([...seasonOrder].sort());
 await modal.locator("circle[aria-label]").first().focus();
 await expect(modal.getByRole("tooltip")).toBeVisible();
 await page.screenshot({path:`/Users/mario_omescu/Documents/Codex/2026-11-26/refactor-the-team-analytics-navigation-to/work/historical-modal-${isMobile?"mobile":"desktop"}.png`,fullPage:true});
 await page.keyboard.press("Escape");
 await expect(modal).toHaveCount(0);
 await expect(scatter.getByLabel("X-axis metric",{exact:true})).toHaveValue("passAccuracy");
 await expect(scatter.getByLabel("Y-axis metric",{exact:true})).toHaveValue("pointsPerMatch");
 await matrix.getByRole("button",{name:"Total shots",exact:true}).click();
 await expect(modal).toBeVisible();
 await modal.getByRole("button",{name:"Close historical evolution",exact:true}).click();
 await expect(modal).toHaveCount(0);
 await matrix.getByRole("button",{name:"Goals",exact:true}).click();
 await page.mouse.click(2,2);
 await expect(modal).toHaveCount(0);
 await expect(scatter.getByRole("group",{name:"Season comparison scatterplot",exact:true})).toBeVisible();
 await page.screenshot({path:`/Users/mario_omescu/Documents/Codex/2026-11-26/refactor-the-team-analytics-navigation-to/work/historical-statistics-${isMobile?"mobile":"desktop"}.png`,fullPage:true});
});
